CREATE TABLE IF NOT EXISTS channels (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  base_url VARCHAR(500) NOT NULL,
  api_key VARBINARY(2048) NOT NULL,
  models JSON NOT NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS members (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  token_hash CHAR(64) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'member',
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  enterprise_limit BIGINT NOT NULL DEFAULT 0,
  enterprise_used BIGINT NOT NULL DEFAULT 0,
  enterprise_reserved BIGINT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_members_token (token_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS policy (
  id TINYINT UNSIGNED PRIMARY KEY,
  blocked_terms JSON NOT NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

INSERT INTO policy (id, blocked_terms)
VALUES (1, JSON_ARRAY('SECRET_MARKER'))
ON DUPLICATE KEY UPDATE id = id;

CREATE TABLE IF NOT EXISTS audits (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  request_id CHAR(32) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  member_id BIGINT UNSIGNED NOT NULL,
  member_name VARCHAR(100) NOT NULL,
  channel_id BIGINT UNSIGNED NULL,
  quota_source VARCHAR(20) NOT NULL,
  model VARCHAR(100) NOT NULL,
  result VARCHAR(40) NOT NULL,
  error_code VARCHAR(40) NOT NULL DEFAULT '',
  http_status INT NOT NULL,
  prompt_tokens BIGINT NOT NULL DEFAULT 0,
  completion_tokens BIGINT NOT NULL DEFAULT 0,
  total_tokens BIGINT NOT NULL DEFAULT 0,
  latency_ms BIGINT NOT NULL DEFAULT 0,
  UNIQUE KEY uq_audits_request (request_id),
  KEY idx_audits_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS config_audits (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  actor VARCHAR(100) NOT NULL,
  action VARCHAR(100) NOT NULL,
  target VARCHAR(100) NOT NULL,
  detail TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
